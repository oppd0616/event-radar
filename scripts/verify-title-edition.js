const assert = require('assert'), fs = require('fs'), vm = require('vm')
const { normalizeTitle } = require('../cloudfunctions/fetchEvents/lib/event-identity')
const { titleEdition, editionConflict } = require('../cloudfunctions/fetchEvents/lib/title-edition')
const source = fs.readFileSync(require.resolve('../cloudfunctions/fetchEvents/index.js'),'utf8')
const start = source.indexOf('function candidateTitleMatches('), end = source.indexOf('\nfunction ',start+1)
const context = { normalizeTitle, titleEdition, editionConflict }
vm.createContext(context); vm.runInContext(source.slice(start,end),context)
const match = context.candidateTitleMatches
const old = 'ComicQuest 05 上海综合同人交流会'
assert(match(old,'ComicQuest5.0综合同人交流会'))
assert(match(old,'第五届ComicQuest综合同人交流会'))
assert(!match(old,'ComicQuest4.0综合同人交流会'))
assert(!match(old,'ComicQuest5.1综合同人交流会'))
assert(!match('2026 ComicQuest05','2025 ComicQuest5.0'))
assert(!match('2026 KPL年度总决赛','2026 LPL年度总决赛'))
assert(!match('2026 KPL小组赛','2026 KPL淘汰赛'))
assert.strictEqual(titleEdition('iPhone 15 Pro').text,normalizeTitle('iPhone 15 Pro'))
assert.strictEqual(titleEdition('2026开发者大会 10月5日').editions.length,0)
assert(!match('第十一届开发者大会','第十二届开发者大会'))
assert(match('2026“數藝華章”青年藝術設計大賽','2026“数艺华章”青年艺术设计大赛'))
assert(match('第七屆新加坡金沙藝術設計大賽','第七届新加坡金沙艺术设计大赛'))
assert(!match('第七屆新加坡金沙藝術設計大賽','第八届新加坡金沙艺术设计大赛'))
assert(match('SOSP: ACM Symposium on Operating Systems Principle','SOSP 2026: ACM Symposium on Operating Systems Principles'))
assert(!match('SOSP 2025: ACM Symposium on Operating Systems Principles','SOSP 2026: ACM Symposium on Operating Systems Principles'))
console.log('Title edition verification passed: equivalent editions match; edition/year/stage/series conflicts stay separate')
