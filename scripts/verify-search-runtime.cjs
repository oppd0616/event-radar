const assert = require('assert')
const { usageRecord, retrievalFailure, failureState } = require('../cloudfunctions/fetchEvents/lib/search-runtime')
const october = usageRecord('2026-10', 1000, 1)
assert(october.fingerprint)
assert.notEqual(october.fingerprint, usageRecord('2026-11', 1000, 1).fingerprint)
assert.equal(october.calls, 1)
const outage = retrievalFailure({ provider: '', errors: ['E11000 fingerprint: null'] }, [{ provider: 'tencent_tokenhub', error: 'http 402: quota exhausted' }])
assert.equal(outage.code, 'DETAIL_SEARCH_UNAVAILABLE')
assert.equal(outage.diagnostics.length, 2)
assert.equal(failureState(outage, { retryCount: 3 }, 0).retryCount, 3)
assert.equal(failureState(outage, {}, 0).lastErrorCode, 'detail_search_unavailable')
assert.equal(retrievalFailure({ provider: 'tencent_wsa', errors: [] }, []), null, 'successful empty search is not an outage')
assert.equal(retrievalFailure({ provider: '', errors: ['timeout'] }, [{ provider: 'tencent_tokenhub', items: [] }]), null, 'successful fallback is not an outage')
assert.equal(failureState(new Error('invalid JSON'), {}, 0).retryCount, 1)
console.log('Search runtime tests passed: unique usage identity, visible provider errors, non-destructive retries, empty-result distinction')
